inline fun <reified T : DialogFragment> AppCompatActivity.showDialogFragment(
    arguments: Bundle.() -> Unit = {}
) {
    @Suppress("DEPRECATION")
    val dialog = T::class.java.newInstance()
    val bundle = Bundle()
    bundle.apply(arguments)
    dialog.arguments = bundle
    dialog.show(supportFragmentManager, T::class.simpleName)
}

inline fun <reified T : DialogFragment> AppCompatActivity.dismissDialogFragment() {
    supportFragmentManager.fragments.forEach {
        if (it is T) {
            it.dismissAllowingStateLoss()
        }
    }
}

fun AppCompatActivity.showDialogFragment(dialogFragment: DialogFragment) {
    dialogFragment.show(supportFragmentManager, dialogFragment::class.simpleName)
}

val WindowManager.windowSize: DisplayMetrics
    get() {
        val displayMetrics = DisplayMetrics()
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            val windowMetrics: WindowMetrics = currentWindowMetrics
            val insets = windowMetrics.windowInsets
                .getInsetsIgnoringVisibility(
                    WindowInsets.Type.systemBars() or WindowInsets.Type.displayCutout()
                )
            val windowWidth = windowMetrics.bounds.width()
            val windowHeight = windowMetrics.bounds.height()
            var insetsWidth = insets.left + insets.right
            var insetsHeight = insets.top + insets.bottom
            if (windowWidth > windowHeight) {
                val tmp = insetsWidth
                insetsWidth = insetsHeight
                insetsHeight = tmp
            }
            displayMetrics.widthPixels = windowWidth - insetsWidth
            displayMetrics.heightPixels = windowHeight - insetsHeight
        } else {
            @Suppress("DEPRECATION")
            defaultDisplay.getMetrics(displayMetrics)
        }
        return displayMetrics
    }

@Suppress("DEPRECATION")
fun Activity.fullScreen() {
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
        window.setDecorFitsSystemWindows(false)
    }
    window.decorView.systemUiVisibility =
        View.SYSTEM_UI_FLAG_LAYOUT_FULLSCREEN or View.SYSTEM_UI_FLAG_LAYOUT_STABLE
    window.clearFlags(
        WindowManager.LayoutParams.FLAG_TRANSLUCENT_STATUS
                or WindowManager.LayoutParams.FLAG_TRANSLUCENT_NAVIGATION
    )
    window.addFlags(WindowManager.LayoutParams.FLAG_DRAWS_SYSTEM_BAR_BACKGROUNDS)
}

/**
 * 设置状态栏颜色
 */
@Suppress("DEPRECATION")
fun Activity.setStatusBarColorAuto(
    @ColorInt color: Int,
    isTransparent: Boolean,
    fullScreen: Boolean = true
) {
    val isLightBar = ColorUtils.isColorLight(color)
    if (fullScreen) {
        if (isTransparent) {
            window.statusBarColor = Color.TRANSPARENT
        } else {
            window.statusBarColor = getCompatColor(R.color.status_bar_bag)
        }
    } else {
        window.statusBarColor = color
    }
    setLightStatusBar(isLightBar)
}

@SuppressLint("ObsoleteSdkInt")
fun Activity.setLightStatusBar(isLightBar: Boolean) {
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
        window.insetsController?.let {
            if (isLightBar) {
                it.setSystemBarsAppearance(
                    WindowInsetsController.APPEARANCE_LIGHT_STATUS_BARS,
                    WindowInsetsController.APPEARANCE_LIGHT_STATUS_BARS
                )
            } else {
                it.setSystemBarsAppearance(
                    0,
                    WindowInsetsController.APPEARANCE_LIGHT_STATUS_BARS
                )
            }
        }
    }
    @Suppress("DEPRECATION")
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) {
        val decorView = window.decorView
        val systemUiVisibility = decorView.systemUiVisibility
        if (isLightBar) {
            decorView.systemUiVisibility =
                systemUiVisibility or View.SYSTEM_UI_FLAG_LIGHT_STATUS_BAR
        } else {
            decorView.systemUiVisibility =
                systemUiVisibility and View.SYSTEM_UI_FLAG_LIGHT_STATUS_BAR.inv()
        }
    }
}

fun Activity.keepScreenOn(on: Boolean) {
    val isScreenOn =
        (window.attributes.flags and WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON) != 0
    if (on == isScreenOn) return
    if (on) {
        window.addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
    } else {
        window.clearFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
    }
}

fun Activity.toggleSystemBar(show: Boolean) {
    if (show) {
        // 先清 legacy 位：阅读页藏栏写下的 SYSTEM_UI_FLAG_FULLSCREEN 不清掉，
        // 框架在窗口重布局/焦点变化时重应用 decorView 的 flag，会把刚显出来的栏再藏回去（时有时无）。
        clearLegacyFullscreenFlags()
    }
    WindowCompat.getInsetsController(window, window.decorView).run {
        if (show) {
            show(WindowInsetsCompat.Type.systemBars())
        } else {
            hide(WindowInsetsCompat.Type.systemBars())
            systemBarsBehavior = BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE
        }
    }
}

/**
 * 清掉阅读页藏栏时写下的 legacy 全屏标志。
 *
 * `upSystemUiVisibility`（ReadBookController）藏栏时直接给 decorView 写 `systemUiVisibility`：
 * `SYSTEM_UI_FLAG_FULLSCREEN`（hideStatusBar && toolBarHide 时）、`SYSTEM_UI_FLAG_HIDE_NAVIGATION`，
 * 且无条件置位 IMMERSIVE / IMMERSIVE_STICKY。退出窗口的显栏（performExit 的普通 show /
 * onDispose 的检查兜底）全走 WindowInsetsController，从来不清这组 legacy 位。只在显栏路径清，藏栏路径一个字不动。
 * 只清隐藏类标志，LAYOUT 系列标志（LAYOUT_STABLE / LAYOUT_FULLSCREEN / LAYOUT_HIDE_NAVIGATION）
 * 保留，edge-to-edge 布局不受影响。
 */
@Suppress("DEPRECATION")
private fun Activity.clearLegacyFullscreenFlags() {
    val decorView = window.decorView
    decorView.systemUiVisibility = decorView.systemUiVisibility and
        View.SYSTEM_UI_FLAG_FULLSCREEN.inv() and
        View.SYSTEM_UI_FLAG_HIDE_NAVIGATION.inv() and
        View.SYSTEM_UI_FLAG_IMMERSIVE.inv() and
        View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY.inv()
}

/**
 * 阅读页退出时的最后一道显栏（onDispose 里调用）。
 *
 * performExit 里已普通 show 过一次；300ms 后检查状态栏是否真的出现了，仍未出现才
 * 再普通 show 一次兜底。退出窗口里只有这两处显栏写操作，不会互相打断。
 * hide 时直接普通藏栏（show=false 时阅读期间栏本就藏着，正常情况无需动作）。
 */
fun Activity.restoreSystemBarsAfterReaderExit(show: Boolean) {
    if (!show) {
        toggleSystemBar(false)
        return
    }
    window.decorView.postDelayed({
        val visible = ViewCompat.getRootWindowInsets(window.decorView)
            ?.isVisible(WindowInsetsCompat.Type.statusBars()) == true
        if (!visible) toggleSystemBar(true)
    }, 300)
}

